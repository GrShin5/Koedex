import Foundation

/// Koedexが初期対応する、表示・音声認識用の言語。
/// rawValueは設定JSONに保存するため、表示文言には使わない。
enum AppLanguage: String, Codable, CaseIterable, Equatable, Identifiable {
    case japanese
    case english

    var id: String { rawValue }

    var localeIdentifier: String {
        switch self {
        case .japanese: return "ja"
        case .english: return "en"
        }
    }

    /// SpeechTranscriberで最初に試すBCP-47 locale。実行時に対応localeへ解決する。
    var preferredSpeechLocaleIdentifier: String {
        switch self {
        case .japanese: return "ja-JP"
        case .english: return "en-US"
        }
    }

    var locale: Locale { Locale(identifier: localeIdentifier) }

    var promptResourceSuffix: String {
        switch self {
        case .japanese: return ""
        case .english: return "_en"
        }
    }

    func localizedDisplayName(for uiLanguage: AppLanguage) -> String {
        switch (self, uiLanguage) {
        case (.japanese, .japanese): return "日本語"
        case (.english, .japanese): return "English"
        case (.japanese, .english): return "Japanese"
        case (.english, .english): return "English"
        }
    }
}

/// 「AIに指示」の通常回答にだけ使う出力言語方針。
/// explicitな音声指示はこの設定より常に優先する。
enum AIOutputLanguage: String, Codable, CaseIterable, Equatable, Identifiable {
    case automatic
    case japanese
    case english

    var id: String { rawValue }

    var fixedLanguage: AppLanguage? {
        switch self {
        case .automatic: return nil
        case .japanese: return .japanese
        case .english: return .english
        }
    }

    static func initialValue(for language: AppLanguage) -> AIOutputLanguage {
        // 初回言語選択は表示・STTだけを確定し、出力は発話に追従させる。
        .automatic
    }

    func localizedDisplayName(for uiLanguage: AppLanguage) -> String {
        switch (self, uiLanguage) {
        case (.automatic, .japanese): return "自動（話した指示に従う）"
        case (.japanese, .japanese): return "日本語"
        case (.english, .japanese): return "English"
        case (.automatic, .english): return "Automatic (follow explicit instruction)"
        case (.japanese, .english): return "Japanese"
        case (.english, .english): return "English"
        }
    }
}

/// UI、STT、AI出力を独立して保存する言語設定。
struct LanguagePreferences: Codable, Equatable {
    var uiLanguage: AppLanguage
    var sttLanguage: AppLanguage
    var aiOutputLanguage: AIOutputLanguage
    /// 通常版の新規インストールで、セットアップ全体を完了したか。
    /// 初回セットアップの途中ではfalseのままにして、戻る操作で言語画面へ戻れるようにする。
    /// 既存設定ではtrueとして扱い、選択画面を再表示しない。
    var hasCompletedInitialLanguageSelection: Bool

    static let newInstall = LanguagePreferences(
        uiLanguage: .japanese,
        sttLanguage: .japanese,
        aiOutputLanguage: .automatic,
        hasCompletedInitialLanguageSelection: false
    )

    static let legacyDefault = LanguagePreferences(
        uiLanguage: .japanese,
        sttLanguage: .japanese,
        aiOutputLanguage: .automatic,
        hasCompletedInitialLanguageSelection: true
    )

    mutating func applyInitialSelection(_ language: AppLanguage) {
        uiLanguage = language
        sttLanguage = language
        aiOutputLanguage = .initialValue(for: language)
    }

    mutating func finalizeInitialLanguageSelection() {
        hasCompletedInitialLanguageSelection = true
    }
}

/// SwiftPMのリソースbundleを明示的に使うローカライザ。
/// SwiftUIの文字列リテラルはWindow側のlocale環境にも追従するが、動的なStringや
/// AppKitのtitleにはこの関数を使用する。
enum AppLocalizer {
    static func text(_ key: String, language: AppLanguage) -> String {
        let bundle = languageBundle(for: language)
        let missingMarker = "__HEYCDEX_MISSING_LOCALIZATION__"
        let translated = bundle.localizedString(
            forKey: key,
            value: missingMarker,
            table: "Localizable"
        )
        guard translated != missingMarker else {
            // 英語UIに日本語キーを露出しない。開発時はrequiredEnglishKeysの回帰で失敗させる。
            return language == .english ? "Localization unavailable" : key
        }
        return translated
    }

    /// 既知のUIキーだけを翻訳し、実行時に生成済みの文言はそのまま表示する。
    static func textOrLiteral(_ value: String, language: AppLanguage) -> String {
        guard hasTranslation(for: value, language: language) else { return value }
        return text(value, language: language)
    }

    static func format(_ key: String, language: AppLanguage, _ arguments: CVarArg...) -> String {
        String(format: text(key, language: language), locale: language.locale, arguments: arguments)
    }

    static func hasTranslation(for key: String, language: AppLanguage) -> Bool {
        let marker = "__HEYCDEX_MISSING_LOCALIZATION__"
        return languageBundle(for: language).localizedString(
            forKey: key,
            value: marker,
            table: "Localizable"
        ) != marker
    }

    private static func languageBundle(for language: AppLanguage) -> Bundle {
        if let url = Bundle.module.url(forResource: language.localeIdentifier, withExtension: "lproj"),
           let bundle = Bundle(url: url) {
            return bundle
        }
        return Bundle.module
    }
}

